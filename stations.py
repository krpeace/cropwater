# ---------------------------------------------------------------------------
# 유틸리티 함수
# ---------------------------------------------------------------------------
def all_station_ids() -> list[int]:
    """전체 66개 지점번호 리스트 반환"""
    return list(STATIONS.keys())


def station_name(stn_id: int) -> str:
    """지점번호 → 지점명"""
    return STATIONS.get(stn_id, f"미확인({stn_id})")


def region_of(stn_id: int) -> str | None:
    """지점번호 → 소속 권역명"""
    for region, ids in REGIONS.items():
        if stn_id in ids:
            return region
    return None


def stations_in_region(region: str) -> list[int]:
    """권역명 → 소속 지점번호 리스트 (전국이면 전체)"""
    if region == "전국":
        return all_station_ids()
    return REGIONS.get(region, [])


def validate():
    """stations.py 자체 검증 — 지점 수 및 매핑 정합성 확인"""
    # 총 지점 수 확인
    assert len(STATIONS) == 66, f"총 지점 수 불일치: {len(STATIONS)}"

    # 권역별 합계 확인
    region_total = sum(len(ids) for ids in REGIONS.values())
    assert region_total == 66, f"권역 소속 지점 합계 불일치: {region_total}"

    # 모든 지점이 정확히 하나의 권역에 소속
    all_in_regions = set()
    for ids in REGIONS.values():
        for stn_id in ids:
            assert stn_id not in all_in_regions, f"중복 소속: {stn_id}"
            all_in_regions.add(stn_id)
    assert all_in_regions == set(STATIONS.keys()), "STATIONS와 REGIONS 불일치"

    # 권역별 지점 수 확인
    expected = {
        "서울경기": 6, "강원영동": 3, "강원영서": 6,
        "충북": 5, "충남": 6,
        "경북": 11, "경남": 11, "전북": 7, "전남": 7,
        "제주": 4,
    }
    for region, count in expected.items():
        actual = len(REGIONS[region])
        assert actual == count, f"{region}: {actual} ≠ {count}"

    print("✓ stations.py 검증 통과 (66개 지점, 10개 권역)")


if __name__ == "__main__":
    validate()
